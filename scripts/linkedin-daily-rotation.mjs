import fs from 'node:fs';
import path from 'node:path';

const ROTATION_FILE = path.resolve('apps/portal/data/linkedin-content/rotation-v1.json');
const QUEUE_FILE = path.resolve('apps/portal/data/linkedin-content/today.json');

function dayOfYear(date) {
  const start = new Date(Date.UTC(date.getUTCFullYear(), 0, 0));
  const diff = date - start;
  return Math.floor(diff / 86400000);
}

function weekOfYear(date) {
  return Math.floor(dayOfYear(date) / 7);
}

function main() {
  const rotation = JSON.parse(fs.readFileSync(ROTATION_FILE, 'utf8'));
  const projects = rotation.projects;
  if (!projects.length) throw new Error('No projects configured in rotation file');

  const now = new Date();
  const doy = dayOfYear(now);
  const woy = weekOfYear(now);

  const projectIndex = doy % projects.length;
  const project = projects[projectIndex];
  const variantIndex = woy % project.variants.length;
  const text = project.variants[variantIndex];

  const postBody = `${text}\n${project.url}\n\n#GNKASG #GNKDINAMO`;

  const output = {
    version: rotation.version,
    generatedAt: now.toISOString(),
    dayOfYear: doy,
    projectId: project.id,
    projectUrl: project.url,
    variantIndex,
    postText: postBody,
    postLength: postBody.length,
    status: 'queued_not_posted',
    note: 'Generated by scripts/linkedin-daily-rotation.mjs. Real posting requires LinkedIn Community Management API access (w_organization_social scope) which is not yet configured. This file is a preview/queue only.',
  };

  fs.mkdirSync(path.dirname(QUEUE_FILE), { recursive: true });
  fs.writeFileSync(QUEUE_FILE, JSON.stringify(output, null, 2));
  console.log(JSON.stringify(output, null, 2));
}

main();
