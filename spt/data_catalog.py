def build_sports():
    """Vraća punu listu sportova s profilima generiranja."""
    sports = []
    for (sid, hr, en, cat, nteam, field, positions, hot, modes, weight) in SPORTS_RAW:
        d = CAT_DEFAULTS[cat]
        # tip aktivnosti: miješaj po omjeru kategorije; udio utakmica raste za timske sportove
        sports.append({
            "id": sid, "hr": hr, "en": en, "cat": cat, "nteam": nteam, "field": list(field),
            "positions": positions, "hot": hot, "modes": modes, "weight": weight,
            "prof": {"dist_match": d[0], "dist_train": d[1], "top": d[2], "dur": d[3], "hr": d[4],
                     "jumps": d[5], "sprints": d[6], "mix": d[7]},
            "tech": TECH_METRICS.get(sid, []),
        })
    return sports

